    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        
        int fila = tblClientes.getSelectedRow();

        if (fila == -1) {
            JOptionPane.showMessageDialog(this,
                    "Primero seleccione un cliente de la tabla");
            return;
        }

        String cedula = txtCedula.getText().trim();
        String nombre = txtNombre.getText().trim();
        String telefono = txtTelefono.getText().trim();
        String correo = txtCorreo.getText().trim();

        if (cedula.isEmpty() || nombre.isEmpty()
                || telefono.isEmpty() || correo.isEmpty()) {

            JOptionPane.showMessageDialog(this,
                    "Debe completar todos los campos");
            return;
        }

        DefaultTableModel modelo
                = (DefaultTableModel) tblClientes.getModel();

        int filaModelo = tblClientes.convertRowIndexToModel(fila);

        for (int i = 0; i < modelo.getRowCount(); i++) {
            if (i != filaModelo
                    && cedula.equals(String.valueOf(modelo.getValueAt(i, 0)))) {
                JOptionPane.showMessageDialog(this,
                        "Ya existe otro cliente con esa cédula");
                return;
            }
        }

        modelo.setValueAt(cedula, filaModelo, 0);
        modelo.setValueAt(nombre, filaModelo, 1);
        modelo.setValueAt(telefono, filaModelo, 2);
        modelo.setValueAt(correo, filaModelo, 3);

        JOptionPane.showMessageDialog(this,
                "Cliente modificado correctamente");

        tblClientes.clearSelection();

        txtCedula.setText("");
        txtNombre.setText("");
        txtTelefono.setText("");
        txtCorreo.setText("");

    }//GEN-LAST:event_btnGuardarActionPerformed

