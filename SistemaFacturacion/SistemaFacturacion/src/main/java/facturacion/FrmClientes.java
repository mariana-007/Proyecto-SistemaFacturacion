    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        String cedula = txtCedula.getText().trim();

        DefaultTableModel modelo
                = (DefaultTableModel) tblClientes.getModel();

        if (cedula.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese una cédula");
            return;
        }

        boolean encontrado = false;

        for (int i = 0; i < modelo.getRowCount(); i++) {

            String cedulaTabla
                    = modelo.getValueAt(i, 0).toString().trim();

            if (cedulaTabla.equals(cedula)) {

                txtNombre.setText(modelo.getValueAt(i, 1).toString());
                txtTelefono.setText(modelo.getValueAt(i, 2).toString());
                txtCorreo.setText(modelo.getValueAt(i, 3).toString());

                tblClientes.setRowSelectionInterval(i, i);

                encontrado = true;
                break;
            }
        }

        if (encontrado) {
            JOptionPane.showMessageDialog(this,
                    "Cliente encontrado correctamente");
        } else {
            JOptionPane.showMessageDialog(this,
                    "Cliente no encontrado. Registros en tabla: "
                    + modelo.getRowCount());
}
    
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        
        int fila = tblClientes.getSelectedRow();

        if (fila == -1) {
            JOptionPane.showMessageDialog(this,
                    "Seleccione un cliente de la tabla para eliminar");
            return;
        }

        int confirmar = JOptionPane.showConfirmDialog(
                this,
                "¿Está seguro de eliminar este cliente?",
                "Confirmar eliminación",
                JOptionPane.YES_NO_OPTION
        );

        if (confirmar == JOptionPane.YES_OPTION) {

            DefaultTableModel modelo
                    = (DefaultTableModel) tblClientes.getModel();

            int filaModelo = tblClientes.convertRowIndexToModel(fila);

            modelo.removeRow(filaModelo);

            txtCedula.setText("");
            txtNombre.setText("");
            txtTelefono.setText("");
            txtCorreo.setText("");

            tblClientes.clearSelection();

            JOptionPane.showMessageDialog(this,
                    "Cliente eliminado correctamente");
        }

    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // TODO add your handling code here:
        String cedula = txtCedula.getText().trim();
        String nombre = txtNombre.getText().trim();
        String telefono = txtTelefono.getText().trim();
        String correo = txtCorreo.getText().trim();

        if (cedula.isEmpty() || nombre.isEmpty()
                || telefono.isEmpty() || correo.isEmpty()) {

            JOptionPane.showMessageDialog(this,
                    "Complete todos los campos");
            return;
        }

        DefaultTableModel modelo
                = (DefaultTableModel) tblClientes.getModel();

        modelo.setColumnIdentifiers(new Object[]{
            "Cédula", "Nombre", "Teléfono", "Correo"
        });

        modelo.addRow(new Object[]{
            cedula, nombre, telefono, correo
        });

        JOptionPane.showMessageDialog(this,
                "Cliente agregado correctamente");

    }//GEN-LAST:event_btnAgregarActionPerformed

