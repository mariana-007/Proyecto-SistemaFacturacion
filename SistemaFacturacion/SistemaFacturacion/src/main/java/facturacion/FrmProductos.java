    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // TODO add your handling code here:

        String codigo = txtCodigo.getText().trim();
        String nombre = txtNombre.getText().trim();
        String precioTexto = txtPrecio.getText().trim();
        String stockTexto = txtStock.getText().trim();

        if (codigo.isEmpty() || nombre.isEmpty()
                || precioTexto.isEmpty() || stockTexto.isEmpty()) {

            JOptionPane.showMessageDialog(this,
                    "Debe completar todos los campos");
            return;
        }

        double precio;
        int stock;

        try {
            precio = Double.parseDouble(precioTexto);
            stock = Integer.parseInt(stockTexto);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                    "El precio debe ser numérico y el stock un número entero");
            return;
        }

        if (!Double.isFinite(precio) || precio <= 0 || stock < 0) {
            JOptionPane.showMessageDialog(this,
                    "El precio debe ser mayor que cero y el stock no puede ser negativo");
            return;
        }

        DefaultTableModel modelo
                = (DefaultTableModel) tblProductos.getModel();

        for (int i = 0; i < modelo.getRowCount(); i++) {

            String codigoExistente
                    = String.valueOf(modelo.getValueAt(i, 0)).trim();

            if (codigoExistente.equalsIgnoreCase(codigo)) {
                JOptionPane.showMessageDialog(this,
                        "Ya existe un producto con ese código");
                return;
            }
        }

        modelo.addRow(new Object[]{
            codigo,
            nombre,
            precio,
            stock
        });

        JOptionPane.showMessageDialog(this,
                "Producto agregado correctamente");

        txtCodigo.setText("");
        txtNombre.setText("");
        txtPrecio.setText("");
        txtStock.setText("");

        txtCodigo.requestFocus();

    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:

        String codigo = txtCodigo.getText().trim();

        if (codigo.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese el código del producto");
            return;
        }

        DefaultTableModel modelo
                = (DefaultTableModel) tblProductos.getModel();

        boolean encontrado = false;

        for (int i = 0; i < modelo.getRowCount(); i++) {

            String codigoTabla
                    = String.valueOf(modelo.getValueAt(i, 0)).trim();

            if (codigoTabla.equalsIgnoreCase(codigo)) {

                txtCodigo.setText(
                        String.valueOf(modelo.getValueAt(i, 0)));

                txtNombre.setText(
                        String.valueOf(modelo.getValueAt(i, 1)));

                txtPrecio.setText(
                        String.valueOf(modelo.getValueAt(i, 2)));

                txtStock.setText(
                        String.valueOf(modelo.getValueAt(i, 3)));

                int filaVista = tblProductos.convertRowIndexToView(i);

                tblProductos.setRowSelectionInterval(filaVista, filaVista);

                encontrado = true;
                break;
            }
        }

        if (encontrado) {
            JOptionPane.showMessageDialog(this,
                    "Producto encontrado correctamente");
        } else {
            tblProductos.clearSelection();

            JOptionPane.showMessageDialog(this,
                    "Producto no encontrado");
        }


    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:

        int fila = tblProductos.getSelectedRow();

        if (fila == -1) {
            JOptionPane.showMessageDialog(this,
                    "Seleccione un producto de la tabla para eliminar");
            return;
        }

        DefaultTableModel modelo
                = (DefaultTableModel) tblProductos.getModel();

        int filaModelo = tblProductos.convertRowIndexToModel(fila);

        String nombreProducto
                = String.valueOf(modelo.getValueAt(filaModelo, 1));

        int confirmar = JOptionPane.showConfirmDialog(
                this,
                "¿Está seguro de eliminar el producto: "
                + nombreProducto + "?",
                "Confirmar eliminación",
                JOptionPane.YES_NO_OPTION
        );

        if (confirmar == JOptionPane.YES_OPTION) {

            modelo.removeRow(filaModelo);

            txtCodigo.setText("");
            txtNombre.setText("");
            txtPrecio.setText("");
            txtStock.setText("");

            tblProductos.clearSelection();

            JOptionPane.showMessageDialog(this,
                    "Producto eliminado correctamente");

            txtCodigo.requestFocus();
        }


    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnMostrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMostrarActionPerformed
        // TODO add your handling code here:

        DefaultTableModel modelo
                = (DefaultTableModel) tblProductos.getModel();

        if (modelo.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this,
                    "No hay productos registrados");
            return;
        }

        tblProductos.clearSelection();

        txtCodigo.setText("");
        txtNombre.setText("");
        txtPrecio.setText("");
        txtStock.setText("");

        if (tblProductos.getRowSorter() != null) {
            tblProductos.getRowSorter().setSortKeys(null);
        }

        JOptionPane.showMessageDialog(this,
                "Mostrando todos los productos registrados: "
                + modelo.getRowCount());


    }//GEN-LAST:event_btnMostrarActionPerformed

