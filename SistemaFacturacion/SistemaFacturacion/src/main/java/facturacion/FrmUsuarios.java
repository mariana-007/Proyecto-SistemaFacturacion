    private void tblUsuariosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblUsuariosMouseClicked
        // Al hacer clic en una fila, los datos pasan a los campos
        int fila = tblUsuarios.getSelectedRow();
        if (fila < 0) {
            return;
        }
        String cedula = tblUsuarios.getValueAt(fila, 0).toString();
        try {
            Usuario u = dao.obtenerPorCedula(cedula);
            if (u != null) {
                txtCedula.setText(u.getCedula());
                txtNombre.setText(u.getNombre());
                txtContrasena.setText(u.getContrasena());
                txtCedula.setEditable(false);   // la llave primaria no se modifica
            }
        } catch (SQLException ex) {
            mostrarErrorBD(ex);
        }
    }//GEN-LAST:event_tblUsuariosMouseClicked

    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        if (!txtCedula.isEditable()) {
            JOptionPane.showMessageDialog(this,
                    "Hay un usuario seleccionado. Pulse Limpiar para agregar uno nuevo.",
                    "Agregar", JOptionPane.INFORMATION_MESSAGE);
            return;
        }
        if (!validarCampos()) {
            return;
        }
        Usuario u = leerFormulario();
        try {
            if (dao.obtenerPorCedula(u.getCedula()) != null) {
                JOptionPane.showMessageDialog(this, "Ya existe un usuario con esa cédula.",
                        "Cédula duplicada", JOptionPane.WARNING_MESSAGE);
                return;
            }
            if (dao.insertar(u)) {
                JOptionPane.showMessageDialog(this, "Usuario agregado correctamente.");
                limpiarFormulario();
                mostrarTodos();
            }
        } catch (SQLException ex) {
            mostrarErrorBD(ex);
        }
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        if (txtCedula.isEditable()) {
            JOptionPane.showMessageDialog(this,
                    "Seleccione un usuario de la tabla para modificarlo.",
                    "Guardar cambios", JOptionPane.INFORMATION_MESSAGE);
            return;
        }
        if (!validarCampos()) {
            return;
        }
        try {
            if (dao.modificar(leerFormulario())) {
                JOptionPane.showMessageDialog(this, "Usuario modificado correctamente.");
                limpiarFormulario();
                mostrarTodos();
            }
        } catch (SQLException ex) {
            mostrarErrorBD(ex);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        if (txtCedula.isEditable()) {
            JOptionPane.showMessageDialog(this,
                    "Seleccione un usuario de la tabla para eliminarlo.",
                    "Eliminar", JOptionPane.INFORMATION_MESSAGE);
            return;
        }
        String cedula = txtCedula.getText().trim();
        try {
            if (dao.contar() <= 1) {
                JOptionPane.showMessageDialog(this,
                        "No se puede eliminar el único usuario: nadie podría ingresar al sistema.",
                        "Eliminar", JOptionPane.WARNING_MESSAGE);
                return;
            }
            int opcion = JOptionPane.showConfirmDialog(this,
                    "¿Eliminar al usuario con cédula " + cedula + "?",
                    "Confirmar eliminación", JOptionPane.YES_NO_OPTION,
                    JOptionPane.WARNING_MESSAGE);
            if (opcion == JOptionPane.YES_OPTION && dao.eliminar(cedula)) {
                JOptionPane.showMessageDialog(this, "Usuario eliminado correctamente.");
                limpiarFormulario();
                mostrarTodos();
            }
        } catch (SQLException ex) {
            mostrarErrorBD(ex);
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

