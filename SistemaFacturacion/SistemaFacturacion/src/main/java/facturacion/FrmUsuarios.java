    /** Vacía los campos, libera la selección y deja listo el formulario para agregar. */
    private void limpiarFormulario() {
        txtCedula.setText("");
        txtNombre.setText("");
        txtContrasena.setText("");
        txtCedula.setEditable(true);
        tblUsuarios.clearSelection();
        txtCedula.requestFocus();
    }

    private void llenarTabla(List<Usuario> lista) {
        DefaultTableModel modelo = (DefaultTableModel) tblUsuarios.getModel();
        modelo.setRowCount(0);
        for (Usuario u : lista) {
            modelo.addRow(new Object[]{u.getCedula(), u.getNombre()});
        }
    }

    private void mostrarTodos() {
        try {
            llenarTabla(dao.listar());
        } catch (SQLException ex) {
            mostrarErrorBD(ex);
        }
    }

    private Usuario leerFormulario() {
        return new Usuario(txtCedula.getText().trim(),
                           txtNombre.getText().trim(),
                           new String(txtContrasena.getPassword()));
    }

    private boolean validarCampos() {
        String cedula = txtCedula.getText().trim();
        String nombre = txtNombre.getText().trim();
        String contrasena = new String(txtContrasena.getPassword());

        if (cedula.isEmpty() || nombre.isEmpty() || contrasena.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios.",
                    "Datos incompletos", JOptionPane.WARNING_MESSAGE);
            return false;
        }
        if (cedula.length() > 20 || nombre.length() > 100 || contrasena.length() > 100) {
            JOptionPane.showMessageDialog(this,
                    "Algún campo excede el largo permitido (cédula 20, nombre y contraseña 100).",
                    "Datos inválidos", JOptionPane.WARNING_MESSAGE);
            return false;
        }
        return true;
    }

    private void mostrarErrorBD(SQLException ex) {
        JOptionPane.showMessageDialog(this,
                "Error de base de datos:\n" + ex.getMessage(),
                "Error", JOptionPane.ERROR_MESSAGE);
    }

    /** Colores y alto de filas de la tabla (se hace a mano, el diseñador no lo permite). */
    private void estiloTabla() {
        javax.swing.table.DefaultTableCellRenderer encabezado = new javax.swing.table.DefaultTableCellRenderer();
        encabezado.setBackground(new java.awt.Color(37, 79, 122));
        encabezado.setForeground(java.awt.Color.WHITE);
        encabezado.setFont(new java.awt.Font("Segoe UI", 1, 12));
        encabezado.setBorder(javax.swing.BorderFactory.createEmptyBorder(4, 8, 4, 8));
        for (int i = 0; i < tblUsuarios.getColumnCount(); i++) {
            tblUsuarios.getColumnModel().getColumn(i).setHeaderRenderer(encabezado);
        }
        tblUsuarios.getTableHeader().setPreferredSize(new java.awt.Dimension(100, 30));
        tblUsuarios.setRowHeight(26);
        tblUsuarios.setSelectionBackground(new java.awt.Color(190, 211, 235));
        tblUsuarios.setSelectionForeground(java.awt.Color.BLACK);
    }

